/**
 * End-to-end check across both PNML implementations.
 *
 * The C# mapper and the JavaScript converter each read and write PNML. If they
 * disagree on a single convention (centre vs top-left, which points an arc
 * carries, how a silent transition is spelled), a diagram silently degrades
 * every time it travels between the AML tree and the canvas. This loads files
 * the mapper produced into the real modeler and compares what comes back.
 *
 * Usage: node tools/verify-interop.mjs [file.pnml]
 * Without an argument it runs the whole fixture set, which covers an empty net,
 * a net without layout, a silent transition, markup characters in ids and
 * names, and moved labels with bendpoints.
 */
import { readdir, readFile } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { serve } from './serve.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The fixture set is generated by `ptmap fixtures`; absent is not fatal. */
async function fixtureFiles() {
  const dir = resolve(repoRoot, 'examples/interop');
  try {
    return (await readdir(dir))
      .filter((name) => name.endsWith('.pnml'))
      .map((name) => resolve(dir, name));
  } catch {
    console.log('note: examples/interop is missing; run "ptmap fixtures examples/interop" to widen this check');
    return [];
  }
}

const files = process.argv[2]
  ? [resolve(process.argv[2])]
  : [resolve(repoRoot, 'examples/quality-gate.pnml'), ...(await fixtureFiles())];

const { server, port } = await serve();
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', (e) => console.error('[pageerror]', e.message));
page.on('console', (m) => {
  if (m.type() === 'error') console.error('[page]', m.text());
});

await page.goto(`http://127.0.0.1:${port}/index.html`);
await page.waitForFunction(() => window.ptnReady === true, null, { timeout: 15000 });

// Both sides are compared after a parse and re-serialize in the same engine.
// The two implementations use different XML writers (System.Xml.Linq vs the
// browser's XMLSerializer) which disagree about the space before "/>", and that
// is formatting, not content. Nothing downstream depends on the two writers
// producing identical bytes: the plugin's echo baseline is the modeler's own
// export compared against later modeler exports, so it never mixes the two.
let failures = 0;

for (const file of files) {
  const expected = (await readFile(file, 'utf8')).trim();

  const [actual, normalizedExpected] = await page.evaluate(async (pnml) => {
    const canonical = (xml) =>
      new XMLSerializer().serializeToString(new DOMParser().parseFromString(xml, 'application/xml'));

    await window.ptn.importPNML(pnml);
    return [canonical(await window.ptn.savePNML()), canonical(pnml)];
  }, expected);

  if (actual === normalizedExpected) {
    console.log(`ok    ${basename(file)}`);
  } else {
    failures++;
    console.log(`FAIL  ${basename(file)}`);
    console.log('--- expected ---');
    console.log(normalizedExpected);
    console.log('--- actual ---');
    console.log(actual);
  }
}

await browser.close();
server.close();

if (failures === 0) {
  console.log(`OK: ${files.length} file(s) survive the modeler unchanged`);
} else {
  console.log(`${failures} of ${files.length} file(s) changed`);
  process.exitCode = 1;
}
